CREATE TABLE audit_log (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha       TIMESTAMPTZ NOT NULL,
    usuario     VARCHAR(50) NOT NULL,
    rol         VARCHAR(20) NOT NULL,
    paciente_id UUID,
    recurso     VARCHAR(20) NOT NULL,
    recurso_id  UUID,
    decision    VARCHAR(25) NOT NULL,
    CONSTRAINT ck_audit_recurso CHECK (recurso IN ('HISTORIA', 'ATENCION', 'RESULTADO', 'ACCESO_EMERGENCIA')),
    CONSTRAINT ck_audit_decision CHECK (decision IN
        ('PERMITIDO_TRATANTE', 'PERMITIDO_EMERGENCIA', 'DENEGADO', 'EMERGENCIA_ACTIVADA'))
);

CREATE INDEX ix_audit_paciente ON audit_log (paciente_id, fecha);
CREATE INDEX ix_audit_usuario ON audit_log (usuario, fecha);

CREATE FUNCTION fn_audit_log_inmutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_log es de solo inserción: no se permite %', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_audit_log_inmutable
    BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION fn_audit_log_inmutable();

CREATE TRIGGER tg_audit_log_sin_truncate
    BEFORE TRUNCATE ON audit_log
    FOR EACH STATEMENT EXECUTE FUNCTION fn_audit_log_inmutable();

CREATE TABLE acceso_emergencia (
    id                   UUID         PRIMARY KEY,
    paciente_id          UUID         NOT NULL REFERENCES paciente (id),
    medico_id            UUID         NOT NULL REFERENCES medico (id),
    usuario              VARCHAR(50)  NOT NULL,
    justificacion        VARCHAR(500) NOT NULL,
    otorgado_en          TIMESTAMPTZ  NOT NULL,
    expira_en            TIMESTAMPTZ  NOT NULL,
    revisado_por         VARCHAR(50),
    revisado_en          TIMESTAMPTZ,
    observacion_revision VARCHAR(500)
);

CREATE INDEX ix_emergencia_vigente ON acceso_emergencia (paciente_id, medico_id, expira_en);
CREATE INDEX ix_emergencia_pendiente ON acceso_emergencia (revisado_en);